use fluent_syntax::{ast, parser};
use proc_macro2::{TokenStream, TokenTree};
use serde::Deserialize;
use std::{
    collections::{BTreeMap, BTreeSet},
    env,
    fmt::Write,
    fs,
    path::{Path, PathBuf},
};
use syn::{Expr, Token, parse::Parser, punctuated::Punctuated};

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;
type Variables = BTreeSet<String>;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Language {
    code: String,
    name: String,
}

#[derive(Default)]
struct Pattern {
    variables: Variables,
    references: Vec<(String, bool)>,
    invalid_functions: Vec<String>,
}

struct Catalog {
    language: Language,
    resources: Vec<PathBuf>,
    messages: BTreeSet<String>,
    patterns: BTreeMap<String, Pattern>,
    variables: BTreeMap<String, Variables>,
}

fn main() {
    if let Err(error) = build() {
        panic!("i18n catalog validation failed: {error}");
    }
    println!("cargo:rerun-if-changed=assets/windows.rc");
    println!("cargo:rerun-if-changed=assets/brand/rustterm.ico");
    // GPUI loads icon resource 1 for the window class. Link it directly into
    // the executable so Explorer and shortcuts use the same application icon.
    // The existing GPUI feature embeds the Windows manifest separately.
    embed_resource::compile_for(
        "assets/windows.rc",
        ["rustterm"],
        embed_resource::ParamsIncludeDirs(["assets"]),
    )
    .manifest_required()
    .expect("Windows application icon resource compilation failed");
}

fn build() -> Result<()> {
    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let locales = root.join("assets/locales");
    println!("cargo:rerun-if-changed={}", locales.display());
    let languages: Vec<Language> =
        serde_json::from_str(&fs::read_to_string(locales.join("languages.json"))?)?;
    let mut registered = BTreeSet::new();
    let mut catalogs = Vec::new();
    for language in languages {
        let code: unic_langid::LanguageIdentifier = language.code.parse()?;
        if code.to_string() != language.code
            || language.code == "system"
            || language.name.trim().is_empty()
            || !registered.insert(language.code.clone())
        {
            return Err(format!(
                "invalid or duplicate language registration: {}",
                language.code
            )
            .into());
        }
        catalogs.push(load_catalog(&locales, language)?);
    }
    let baseline = catalogs
        .iter()
        .find(|catalog| catalog.language.code == "en")
        .ok_or("the English (en) catalog must be registered")?;
    for catalog in &catalogs {
        compare_catalogs(baseline, catalog)?;
    }

    let mut constants = BTreeMap::new();
    for id in &baseline.messages {
        let constant = id.replace('-', "_").to_ascii_uppercase();
        if let Some(previous) = constants.insert(constant.clone(), id.clone()) {
            return Err(
                format!("{previous} and {id} generate the same constant {constant}").into(),
            );
        }
    }
    let source = root.join("src");
    println!("cargo:rerun-if-changed={}", source.display());
    for path in files_with_extension(&source, "rs")? {
        let tokens: TokenStream = fs::read_to_string(&path)?
            .parse()
            .map_err(|error| format!("{}: {error}", path.display()))?;
        validate_calls(tokens, &path, baseline, &constants)?;
    }

    let mut generated =
        String::from("// Generated by build.rs.\nstatic LOCALES: &[LocaleDefinition] = &[\n");
    for catalog in &catalogs {
        writeln!(
            generated,
            "LocaleDefinition {{ code: {:?}, native_name: {:?}, resources: &[",
            catalog.language.code, catalog.language.name
        )?;
        for path in &catalog.resources {
            writeln!(
                generated,
                "include_str!({:?}),",
                path.to_str().ok_or("locale path is not UTF-8")?
            )?;
        }
        generated.push_str("] },\n");
    }
    generated.push_str("];\nstatic STATIC_MESSAGES: &[&str] = &[\n");
    for id in &baseline.messages {
        if baseline.variables[id].is_empty() {
            writeln!(generated, "{id:?},")?;
        }
    }
    generated.push_str("];\npub mod messages {\n");
    for (constant, id) in &constants {
        writeln!(generated, "pub const {constant}: &str = {id:?};")?;
    }
    generated.push_str("}\n");
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("i18n_catalogs.rs"),
        generated,
    )?;
    Ok(())
}

fn files_with_extension(directory: &Path, extension: &str) -> Result<Vec<PathBuf>> {
    let mut files = Vec::new();
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let kind = entry.file_type()?;
        if kind.is_dir() {
            files.extend(files_with_extension(&entry.path(), extension)?);
        } else if kind.is_file()
            && entry
                .path()
                .extension()
                .is_some_and(|value| value == extension)
        {
            files.push(entry.path());
        }
    }
    files.sort();
    Ok(files)
}

fn load_catalog(directory: &Path, language: Language) -> Result<Catalog> {
    let resources = files_with_extension(&directory.join(&language.code), "ftl")?;
    if resources.is_empty() {
        return Err(format!("{} has no Fluent resources", language.code).into());
    }
    let mut catalog = Catalog {
        language,
        resources,
        messages: BTreeSet::new(),
        patterns: BTreeMap::new(),
        variables: BTreeMap::new(),
    };
    // FluentBundle shares a namespace for messages, terms, and functions.
    let mut identifiers = BTreeSet::from(["NUMBER".to_owned()]);
    for path in &catalog.resources {
        let source = fs::read_to_string(path)?;
        let resource = parser::parse(source.as_str())
            .map_err(|(_, errors)| format!("{}: {errors:?}", path.display()))?;
        for entry in resource.body {
            let (id, value, attributes) = match entry {
                ast::Entry::Message(message) => {
                    let id = message.id.name.to_owned();
                    let value = message
                        .value
                        .ok_or_else(|| format!("{}: {id} needs a message value", path.display()))?;
                    catalog.messages.insert(id.clone());
                    (id, value, message.attributes)
                }
                ast::Entry::Term(term) => {
                    (format!("-{}", term.id.name), term.value, term.attributes)
                }
                _ => continue,
            };
            if !identifiers.insert(id.trim_start_matches('-').to_owned()) {
                return Err(format!("{}: duplicate Fluent identifier {id}", path.display()).into());
            }
            catalog
                .patterns
                .insert(id.clone(), Pattern::collect(&value));
            for attribute in attributes {
                let key = format!("{id}.{}", attribute.id.name);
                if catalog
                    .patterns
                    .insert(key.clone(), Pattern::collect(&attribute.value))
                    .is_some()
                {
                    return Err(
                        format!("{}: duplicate Fluent attribute {key}", path.display()).into(),
                    );
                }
            }
        }
    }
    for (id, pattern) in &catalog.patterns {
        if !pattern.invalid_functions.is_empty() {
            return Err(format!(
                "{}: {id}: {}",
                catalog.language.code,
                pattern.invalid_functions.join("; ")
            )
            .into());
        }
        let variables = resolve_variables(id, &catalog.patterns, &mut BTreeSet::new())
            .map_err(|error| format!("{}: {error}", catalog.language.code))?;
        catalog.variables.insert(id.clone(), variables);
    }
    Ok(catalog)
}

impl Pattern {
    fn collect(pattern: &ast::Pattern<&str>) -> Self {
        let mut collected = Self::default();
        collected.pattern(pattern);
        collected
    }

    fn pattern(&mut self, pattern: &ast::Pattern<&str>) {
        for element in &pattern.elements {
            if let ast::PatternElement::Placeable { expression } = element {
                self.expression(expression);
            }
        }
    }

    fn expression(&mut self, expression: &ast::Expression<&str>) {
        match expression {
            ast::Expression::Inline(inline) => self.inline(inline),
            ast::Expression::Select { selector, variants } => {
                self.inline(selector);
                for variant in variants {
                    self.pattern(&variant.value);
                }
            }
        }
    }

    fn inline(&mut self, inline: &ast::InlineExpression<&str>) {
        match inline {
            ast::InlineExpression::VariableReference { id } => {
                self.variables.insert(id.name.to_owned());
            }
            ast::InlineExpression::MessageReference { id, attribute } => {
                self.reference(id.name.to_owned(), attribute, true);
            }
            ast::InlineExpression::TermReference {
                id,
                attribute,
                arguments,
            } => {
                // Terms have a local argument scope; their variables do not
                // become external arguments of the referring message.
                self.reference(format!("-{}", id.name), attribute, false);
                if let Some(arguments) = arguments {
                    self.arguments(arguments);
                }
            }
            ast::InlineExpression::FunctionReference { id, arguments } => {
                // Keep this in sync with Catalog::new's add_builtins call.
                if id.name != "NUMBER" {
                    self.invalid_functions
                        .push(format!("unsupported Fluent function {}", id.name));
                } else if arguments.positional.len() != 1
                    || matches!(
                        arguments.positional.first(),
                        Some(ast::InlineExpression::StringLiteral { .. })
                    )
                {
                    self.invalid_functions
                        .push("NUMBER requires one numeric argument".into());
                }
                self.arguments(arguments);
            }
            ast::InlineExpression::Placeable { expression } => self.expression(expression),
            ast::InlineExpression::StringLiteral { .. }
            | ast::InlineExpression::NumberLiteral { .. } => {}
        }
    }

    fn reference(
        &mut self,
        mut id: String,
        attribute: &Option<ast::Identifier<&str>>,
        inherits: bool,
    ) {
        if let Some(attribute) = attribute {
            id.push('.');
            id.push_str(attribute.name);
        }
        self.references.push((id, inherits));
    }

    fn arguments(&mut self, arguments: &ast::CallArguments<&str>) {
        for argument in &arguments.positional {
            self.inline(argument);
        }
        for argument in &arguments.named {
            self.inline(&argument.value);
        }
    }
}

fn resolve_variables(
    id: &str,
    patterns: &BTreeMap<String, Pattern>,
    visiting: &mut BTreeSet<String>,
) -> Result<Variables> {
    if !visiting.insert(id.to_owned()) {
        return Err(format!("cyclic Fluent reference involving {id}").into());
    }
    let pattern = patterns
        .get(id)
        .ok_or_else(|| format!("unknown Fluent reference {id}"))?;
    let mut variables = pattern.variables.clone();
    for (reference, inherits) in &pattern.references {
        let referenced = resolve_variables(reference, patterns, visiting)?;
        if *inherits {
            variables.extend(referenced);
        }
    }
    visiting.remove(id);
    Ok(variables)
}

fn compare_catalogs(baseline: &Catalog, translated: &Catalog) -> Result<()> {
    let expected = &baseline.messages;
    let actual = &translated.messages;
    if expected != actual {
        return Err(format!(
            "{} differs from en: missing {:?}; unexpected {:?}",
            translated.language.code,
            expected.difference(actual).collect::<Vec<_>>(),
            actual.difference(expected).collect::<Vec<_>>()
        )
        .into());
    }
    for id in &baseline.messages {
        let expected = &baseline.variables[id];
        let actual = &translated.variables[id];
        if expected != actual {
            return Err(format!(
                "{}: {id} expects {expected:?} arguments, found {actual:?}",
                translated.language.code
            )
            .into());
        }
    }
    Ok(())
}

fn validate_calls(
    tokens: TokenStream,
    path: &Path,
    catalog: &Catalog,
    constants: &BTreeMap<String, String>,
) -> Result<()> {
    let tokens: Vec<_> = tokens.into_iter().collect();
    for (index, token) in tokens.iter().enumerate() {
        if let TokenTree::Ident(name) = token {
            let name = name.to_string();
            let arguments = match (name.as_str(), tokens.get(index + 1), tokens.get(index + 2)) {
                ("tr", Some(TokenTree::Group(arguments)), _) => Some((arguments, false)),
                (
                    "trf" | "msg",
                    Some(TokenTree::Punct(mark)),
                    Some(TokenTree::Group(arguments)),
                ) if mark.as_char() == '!' => Some((arguments, true)),
                _ => None,
            };
            if let Some((arguments, formatted)) = arguments {
                let arguments = normalize_error_fields(arguments.stream());
                let parsed = Punctuated::<Expr, Token![,]>::parse_terminated.parse2(arguments);
                // Function definitions and macro definitions are not call sites.
                if let Ok(arguments) = parsed
                    && let Some(first) = arguments.first()
                    && let Some(id) = message_id(first, constants)
                {
                    let expected = catalog
                        .variables
                        .get(&id)
                        .ok_or_else(|| format!("{}: unknown message {id}", path.display()))?;
                    let mut supplied = BTreeSet::new();
                    for argument in arguments.iter().skip(1) {
                        let Expr::Assign(argument) = argument else {
                            return Err(format!(
                                "{}: {name}!({id}) requires named arguments",
                                path.display()
                            )
                            .into());
                        };
                        let Expr::Path(argument) = argument.left.as_ref() else {
                            return Err(format!(
                                "{}: invalid argument name for {id}",
                                path.display()
                            )
                            .into());
                        };
                        let identifier = argument
                            .path
                            .get_ident()
                            .ok_or("message argument names must be identifiers")?
                            .to_string();
                        if !supplied.insert(identifier.clone()) {
                            return Err(format!(
                                "{}: duplicate argument {identifier} for {id}",
                                path.display()
                            )
                            .into());
                        }
                    }
                    if supplied != *expected || !formatted && !expected.is_empty() {
                        return Err(format!(
                            "{}: {name}({id}) expects {expected:?} arguments, found {supplied:?}",
                            path.display()
                        )
                        .into());
                    }
                }
            }
        }
        if let TokenTree::Group(group) = token {
            validate_calls(group.stream(), path, catalog, constants)?;
        }
    }
    Ok(())
}

fn message_id(expression: &Expr, constants: &BTreeMap<String, String>) -> Option<String> {
    match expression {
        Expr::Path(path) => constants
            .get(&path.path.segments.last()?.ident.to_string())
            .cloned(),
        Expr::Lit(literal) => match &literal.lit {
            syn::Lit::Str(value) => Some(value.value()),
            _ => None,
        },
        _ => None,
    }
}

fn normalize_error_fields(tokens: TokenStream) -> TokenStream {
    // thiserror permits `.field` and `.0` expressions inside error attributes.
    // Prefix them for syn without changing the tokens compiled by Rust.
    let tokens: Vec<_> = tokens.into_iter().collect();
    let mut normalized = TokenStream::new();
    for (index, token) in tokens.iter().enumerate() {
        if matches!(token, TokenTree::Punct(mark) if mark.as_char() == '.')
            && matches!(tokens.get(index.wrapping_sub(1)), Some(TokenTree::Punct(mark)) if mark.as_char() == '=')
        {
            normalized.extend([TokenTree::Ident(proc_macro2::Ident::new(
                "self",
                token.span(),
            ))]);
        }
        normalized.extend([token.clone()]);
    }
    normalized
}
